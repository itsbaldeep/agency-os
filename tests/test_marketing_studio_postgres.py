    def test_worker_draft_execution_keeps_source_facts_and_revision(self):
        cur = self.cursor()
        cur.execute("INSERT INTO marketing_brand_profiles(brand_id,profile) VALUES (202,%s)", (json.dumps({"positioning": "South tools"}),))
        cur.execute("INSERT INTO marketing_work_items(brand_id,kind,channel,title,brief) VALUES (202,'social_post','linkedin','South draft',%s) RETURNING id", (json.dumps({"approved_facts": ["South fact"]}),))
        item_id = cur.fetchone()["id"]
        conn = self._dashboard_conn()
        result = workflow.handle({"params": {"brand_id": 202, "item_id": item_id, "revision": 1}}, lambda: conn)
        self.assertTrue(result["ok"], result)
        cur = self.cursor()
        cur.execute("SELECT title,body,revision,brief FROM marketing_work_items WHERE id=%s AND brand_id=202", (item_id,))
        row = cur.fetchone()
        self.assertEqual(row["title"], "South draft")
        self.assertIn("South fact", row["body"])
        self.assertEqual(row["revision"], 2)
        self.assertFalse(json.loads(row["brief"] if isinstance(row["brief"], str) else json.dumps(row["brief"])).get("publish", False))


