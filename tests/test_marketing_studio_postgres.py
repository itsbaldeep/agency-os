def _core_env():
    values = {}
    try:
        for raw in Path("/home/agency/.config/agency/core.env").read_text().splitlines():
            if "=" in raw and not raw.lstrip().startswith("#"):
                key, value = raw.split("=", 1)
                values[key.strip()] = value.strip().strip('"').strip("'")
    except OSError:
        return {}
    return values


def _dsn():
    env = _core_env()
    if not env.get("POSTGRES_PASSWORD"):
        return None
    return {
        "host": os.environ.get("MARKETING_FIXTURE_DB_HOST", "100.64.0.1"),
        "dbname": env.get("POSTGRES_DB", "agencyos"),
        "user": env.get("POSTGRES_USER", "agency"),
        "password": env["POSTGRES_PASSWORD"],
    }


def _migration_sql(path: Path) -> str:
    sql = path.read_text()
    return re.sub(r"(?im)^\s*(BEGIN|COMMIT);\s*$", "", sql)


@unittest.skipUnless(psycopg2 and _dsn(), "isolated PostgreSQL fixture is unavailable")
class MarketingStudioPostgresTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.conn = psycopg2.connect(**_dsn())
        cls.conn.autocommit = False
        cls.schema = "marketing_test_rollback"
        cur = cls.conn.cursor()
        cur.execute("CREATE SCHEMA %s" % cls.schema)
        cur.execute("SET search_path TO %s,public" % cls.schema)
        cur.execute("CREATE TABLE brands (id integer PRIMARY KEY, name text NOT NULL)")
        cur.execute("CREATE TABLE tasks (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, type text NOT NULL, status text NOT NULL, params jsonb NOT NULL, triggered_by text)")
        cur.execute(_migration_sql(ROOT / "infra/migrations/020_marketing_studio.sql"))
        cur.execute(_migration_sql(ROOT / "infra/migrations/021_marketing_channels.sql"))
        cur.execute("INSERT INTO brands(id,name) VALUES (101,'Fixture North'),(202,'Fixture South')")
        # Keep the schema isolated for every following statement.  The final
        # transaction is rolled back and the schema is dropped with it.
        cur.execute("SET search_path TO %s,public" % cls.schema)

    @classmethod
    def tearDownClass(cls):
        cls.conn.rollback()
        cur = cls.conn.cursor()
        cur.execute("SELECT to_regnamespace(%s)", (cls.schema,))
        assert cur.fetchone()[0] is None, "rollback-only schema survived"
        cls.conn.close()

    @classmethod
    def cursor(cls):
        cur = cls.conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor)
        cur.execute("SET search_path TO %s,public" % cls.schema)
        return cur

    class _TxConnection:
        def __init__(self, conn, schema):
            self._conn, self._schema = conn, schema

        def cursor(self, *args, **kwargs):
            kwargs.setdefault("cursor_factory", psycopg2.extras.RealDictCursor)
            cur = self._conn.cursor(*args, **kwargs)
            cur.execute("SET search_path TO %s,public" % self._schema)
            return cur

        def commit(self):
            pass

        def rollback(self):
            self._conn.rollback()

        def close(self):
            pass

    def _dashboard_conn(self):
        return self._TxConnection(self.conn, self.schema)

    def setUp(self):
        self.cursor().execute("SAVEPOINT marketing_test")

    def tearDown(self):
        self.cursor().execute("ROLLBACK TO SAVEPOINT marketing_test")

